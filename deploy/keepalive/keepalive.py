#!/usr/bin/env python3
# ── ParvizOS · keep-alive ─────────────────────────────────────────
# Держим ~3 ГБ RAM занятыми, чтобы Oracle не счёл Always Free инстанс
# простаивающим и не забрал его. Для ARM-шейпов (A1) память учитывается
# в правиле простоя, поэтому держать её выше 20% — надёжный способ.
#
# Нужно ТОЛЬКО если ты НЕ перешёл на Pay As You Go. PAYG отменяет правило
# про простой вообще — это надёжнее, и тогда keep-alive не нужен.
#
# Ест ~3 ГБ памяти (у сервера 12 ГБ — с запасом) и почти ноль CPU.
import time

GIB = 1024 * 1024 * 1024
SIZE = 3 * GIB  # 3 ГБ — заметно выше 20% от 12 ГБ

# Выделяем буфер и касаемся каждой страницы уникальным значением, чтобы
# страницы реально осели в RAM и их не «схлопнула» дедупликация одинаковых
# страниц (KSM), если она вдруг включена.
buf = bytearray(SIZE)
for i in range(0, SIZE, 4096):
    buf[i] = (i >> 12) & 0xFF

# Раз в час слегка «шевелим» память — гарантированно остаётся горячей.
while True:
    time.sleep(3600)
    for i in range(0, SIZE, 4096):
        buf[i] = (buf[i] + 1) & 0xFF
