/**
 * Хук запуска сервера Next.js (выполняется один раз при старте, до запросов).
 *
 * Прогоняем миграции и включаем WAL сразу на старте, а не лениво при первом
 * запросе. Это важно для непрерывной репликации базы в облако (Litestream):
 * ей нужен режим WAL с самого начала, ещё до того как кто-то откроет
 * страницу. Ошибки глушим — на здоровье приложения это не влияет.
 */
export async function register() {
  if (process.env.NEXT_RUNTIME !== "nodejs") return;
  try {
    const { schemaReady } = await import("@/db");
    await schemaReady();
  } catch {
    // Молча: миграции/WAL всё равно применятся при первом обращении к БД.
  }
}
